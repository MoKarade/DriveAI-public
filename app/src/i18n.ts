export type Langue = 'fr' | 'en';

const CLE = 'driveai.langue';

export function langueCourante(): Langue {
  try {
    if (typeof localStorage === 'undefined') return 'fr';
    const brut = localStorage.getItem(CLE);
    return brut === 'fr' || brut === 'en' ? brut : 'fr';
  } catch {
    return 'fr';
  }
}

export function changerLangue(l: Langue): void {
  const valide: Langue = l === 'en' ? 'en' : 'fr';
  try {
    if (typeof localStorage === 'undefined') return;
    localStorage.setItem(CLE, valide);
  } catch {
    /* stockage indisponible ou quota atteint : dégradation silencieuse */
  }
}

